create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 12),
  job text not null default 'warrior',
  wave int not null check (wave >= 1 and wave <= 80),
  kills int not null check (kills >= 0 and kills <= 20000),
  seconds int not null check (seconds >= 20 and seconds <= 18000),
  day text not null,
  seed bigint not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists scores_day_wave_idx on public.scores (day, wave desc, kills desc);

alter table public.scores enable row level security;

drop policy if exists "read all" on public.scores;
create policy "read all" on public.scores for select using (true);

drop policy if exists "insert own" on public.scores;
create policy "insert own" on public.scores for insert with check (true);
